// Translate a clinic-file sentence. Returns { text, translated }.
function tr(lang, s) {
  s = String(s == null ? '' : s);
  if (lang === 'en' || !TR[lang]) return { text: s, translated: true };
  if (TR[lang][s]) return { text: TR[lang][s], translated: true };
  const to = { hi: ' से ', te: ' నుండి ', ar: ' إلى ', fr: ' à ' }[lang] || ' to ';
  const m = s.match(/^(Rs [\d,]+|\d{1,2}:\d{2} [ap]m) to (Rs [\d,]+|\d{1,2}:\d{2} [ap]m)$/);
  if (m) return { text: m[1] + to + m[2], translated: true };
  if (/^Rs [\d,]+$/.test(s)) return { text: s, translated: true };
  return { text: s, translated: false };
}
